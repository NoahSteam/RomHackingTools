#!/usr/bin/env python3
# Area 2 round 11 instrument: builds nzmask_audit.cpp from the vendored op.cc: PcodeOp::getNZMaskLocal's switch is cut out verbatim and wrapped
# in a function of (op-code, sizes, the inputs' non-zero masks, whether input 1 is a constant), then the generated program checks it against
# every value the op can produce from values inside the masks (exhaustive at one byte for all masks, sampled at 2, 4 and 8 bytes).
# usage: nzmask_audit.py <ghidra-decompiler/cpp dir> <out.cpp>
import re, sys
cpp, out = sys.argv[1], sys.argv[2]
src = open(cpp + "/op.cc").read()
i = src.index("uintb PcodeOp::getNZMaskLocal(bool cliploop) const")
j = src.index("\n}\n", i)
body = src[i:j + 3]
# the switch, with the node accessors replaced by arguments
sw = body[body.index("  switch(opcode->getOpcode()) {"):]
sw = sw.replace("opcode->getOpcode()", "opc")
sw = sw.replace("getIn(0)->getNZMask()", "NZ0").replace("getIn(1)->getNZMask()", "NZ1")
sw = sw.replace("getIn(0)->getSize()", "SZ0").replace("getIn(1)->getSize()", "SZ1")
sw = sw.replace("getIn(1)->isConstant()", "ISC1").replace("getIn(1)->getOffset()", "C1")
# drop the cases that read the op's own state
sw = re.sub(r"  case CPUI_MULTIEQUAL:.*?(?=  case CPUI_CALL:)", "", sw, flags=re.S)
sw = re.sub(r"  case CPUI_CALL:.*?(?=  default:)", "", sw, flags=re.S)
sw = sw[:sw.rindex("  return resmask;")]
assert "getIn" not in sw and "inrefs" not in sw, sw
prog = r'''// generated by nzmask_audit.py from op.cc -- do not edit
#include "libdecomp.hh"
#include <cstdio>
#include <cstdlib>
#include <random>
#include <string>
#include <map>
using namespace ghidra;
static uintb nzlocal(OpCode opc, int size, int SZ0, int SZ1, uintb NZ0, uintb NZ1, bool ISC1, uintb C1) {
  int4 sa, sz1, sz2; uintb resmask, val;
  uintb fullmask = calc_mask(size);
''' + sw + r'''
  return resmask;
}
static uintb M(int sz) { return sz >= 8 ? ~(uintb)0 : (((uintb)1 << (8 * sz)) - 1); }
static int64_t SX(uintb v, int sz) { if (sz >= 8) return (int64_t)v; uintb s = (uintb)1 << (8 * sz - 1); return (int64_t)((v ^ s) - s); }
static uintb eval(OpCode opc, int outsz, int s0, int s1, uintb a, uintb b, bool &ok) {
  uintb m = M(outsz); ok = true;
  switch (opc) {
    case CPUI_COPY: return a;
    case CPUI_INT_ZEXT: return a;
    case CPUI_INT_SEXT: return (uintb)SX(a, s0) & m;
    case CPUI_INT_XOR: return a ^ b; case CPUI_INT_OR: return a | b; case CPUI_INT_AND: return a & b;
    case CPUI_INT_LEFT: return b >= (uintb)(8 * outsz) ? 0 : (a << b) & m;
    case CPUI_INT_RIGHT: return b >= (uintb)(8 * s0) ? 0 : a >> b;
    case CPUI_INT_SRIGHT: { uintb sh = b >= (uintb)(8 * s0) ? 8 * s0 - 1 : b; return (uintb)(SX(a, s0) >> sh) & m; }
    case CPUI_INT_DIV: if (b == 0) { ok = false; return 0; } return a / b;
    case CPUI_INT_REM: if (b == 0) { ok = false; return 0; } return a % b;
    case CPUI_POPCOUNT: return __builtin_popcountll(a);
    case CPUI_LZCOUNT: return a == 0 ? 8 * s0 : __builtin_clzll(a) - (64 - 8 * s0);
    case CPUI_SUBPIECE: return b >= 8 ? 0 : (a >> (8 * b)) & m;
    case CPUI_PIECE: return ((s1 >= 8 ? 0 : a << (8 * s1)) | b) & m;
    case CPUI_INT_MULT: return (a * b) & m;
    case CPUI_INT_ADD: return (a + b) & m;
    default: ok = false; return 0;
  }
}
int main(int argc, char **argv) {
  std::mt19937_64 rng(argc > 1 ? strtoull(argv[1], 0, 0) : 1);
  long rnd = argc > 2 ? atol(argv[2]) : 200000;
  struct Op { OpCode opc; const char *name; bool constb; };   // constb: the shift/subpiece amount is a constant input
  std::vector<Op> ops = {{CPUI_COPY,"COPY",0},{CPUI_INT_ZEXT,"ZEXT",0},{CPUI_INT_SEXT,"SEXT",0},{CPUI_INT_XOR,"XOR",0},{CPUI_INT_OR,"OR",0},{CPUI_INT_AND,"AND",0},
    {CPUI_INT_LEFT,"LEFT",1},{CPUI_INT_RIGHT,"RIGHT",1},{CPUI_INT_SRIGHT,"SRIGHT",1},{CPUI_INT_DIV,"DIV",0},{CPUI_INT_DIV,"DIV const",1},{CPUI_INT_REM,"REM",0},{CPUI_POPCOUNT,"POPCOUNT",0},{CPUI_LZCOUNT,"LZCOUNT",0},
    {CPUI_SUBPIECE,"SUBPIECE",1},{CPUI_PIECE,"PIECE",0},{CPUI_INT_MULT,"MULT",0},{CPUI_INT_MULT,"MULT const",1},{CPUI_INT_ADD,"ADD",0}};
  std::map<std::string, std::pair<long,long>> G; std::map<std::string, std::string> EX;
  for (int sz : {1, 2, 4, 8}) for (const Op &o : ops) {
    int outsz = sz, s0 = sz, s1 = sz;
    if (o.opc == CPUI_INT_ZEXT || o.opc == CPUI_INT_SEXT) { if (sz == 8) continue; outsz = sz * 2 > 8 ? 8 : sz * 2; }
    if (o.opc == CPUI_SUBPIECE) { if (sz == 1) continue; outsz = sz / 2; s1 = 4; }
    if (o.opc == CPUI_PIECE) { if (sz > 4) continue; outsz = sz * 2; }
    if (o.opc == CPUI_INT_LEFT || o.opc == CPUI_INT_RIGHT || o.opc == CPUI_INT_SRIGHT) s1 = 4;
    if (o.opc == CPUI_POPCOUNT || o.opc == CPUI_LZCOUNT) outsz = sz;
    uintb m0 = M(s0), m1 = M(s1);
    char key[64]; std::snprintf(key, sizeof key, "%s sz%d", o.name, sz);
    long n = 0, bad = 0;
    auto check = [&](uintb NZ0, uintb NZ1) {
      // the mask the engine computes, and every value the op yields for a (subset of NZ0) and b (subset of NZ1; the constant itself when constb)
      uintb R = nzlocal(o.opc, outsz, s0, s1, NZ0, NZ1, o.constb, NZ1);
      // enumerate submasks (all of them when few, else a sample including the extremes)
      std::vector<uintb> as, bs;
      auto subs = [&](uintb m, std::vector<uintb> &v) {
        int pc = __builtin_popcountll(m);
        if (pc <= 8) { uintb s = m; for (;;) { v.push_back(s); if (s == 0) break; s = (s - 1) & m; } }
        else { v.push_back(0); v.push_back(m); for (int i = 0; i < 40; i++) v.push_back(rng() & m); uintb low = m & (0 - m); v.push_back(low); v.push_back(m ^ low); }
      };
      subs(NZ0, as);
      if (o.constb) bs.push_back(NZ1); else subs(NZ1, bs);
      for (uintb a : as) for (uintb b : bs) {
        bool ok; uintb v = eval(o.opc, outsz, s0, s1, a, b, ok);
        if (!ok) continue;
        n++;
        if (v & ~R) { bad++; if (EX[key].empty()) { char buf[200]; std::snprintf(buf, sizeof buf, "NZ0=%llx NZ1=%llx a=%llx b=%llx -> %llx not in mask %llx", (unsigned long long)NZ0, (unsigned long long)NZ1, (unsigned long long)a, (unsigned long long)b, (unsigned long long)v, (unsigned long long)R); EX[key] = buf; } return; }
      }
    };
    if (sz == 1) { for (uintb x = 0; x < 256; x++) for (uintb y = 0; y < 256; y++) { if (o.constb && (o.opc == CPUI_INT_DIV) && y == 0) continue; check(x, y); } }
    else {
      std::vector<uintb> ed = {0, 1, 2, 3, 0xff, 0x100, 0x7f, 0x80, 0xff00, m0, m0 >> 1, (m0 >> 1) + 1, m0 - 1, m0 >> 8, m1, m1 >> 1, m1 >> 4, 0x5555555555555555ull & m0, 0xAAAAAAAAAAAAAAAAull & m0, 0xF0F0F0F0F0F0F0F0ull & m0, 0xFFFF0000ull & m0, 0xFFFF & m0, 0x80000000ull & m0};
      for (uintb &v : ed) v &= m0;
      for (long i = 0; i < rnd; i++) {
        uintb a = (i % 3 == 0) ? (rng() & m0) : (i % 3 == 1) ? ed[rng() % ed.size()] : ((rng() & m0) >> (rng() % (8 * s0))) << (rng() % 4);
        uintb b = (i % 4 == 0) ? (rng() & m1) : (i % 4 == 1) ? (ed[rng() % ed.size()] & m1) : (i % 4 == 2) ? (rng() % (8 * s0 + 3)) : (((rng() & m1) >> (rng() % (8 * s1))) << (rng() % 3));
        if (o.opc == CPUI_SUBPIECE) b = rng() % (s0 + 1);
        a &= m0; b &= m1;
        if (o.constb && o.opc == CPUI_INT_DIV && b == 0) continue;
        check(a, b);
      }
    }
    G[key] = std::make_pair(n, bad);
  }
  // the shift amounts by which a signed right shift of a value that may be negative is wrongly said to give zero
  for (int sz : {1, 2, 4, 8}) {
    std::string bad;
    for (uintb c = 0; c < 200; c++) {
      uintb NZ0 = M(sz);   // anything possible, the sign bit included
      uintb R = nzlocal(CPUI_INT_SRIGHT, sz, sz, 4, NZ0, c, true, c);
      uintb want = c >= (uintb)(8 * sz) ? M(sz) : (M(sz) >> c) | (M(sz) ^ (M(sz) >> c));   // sign fill: every bit possible
      if ((M(sz) & ~R) != 0 && want == M(sz)) { char b[32]; std::snprintf(b, sizeof b, "%llu ", (unsigned long long)c); if (bad.size() < 60) bad += b; }
    }
    std::printf("SRIGHT by a constant, value of %d bytes, mask full: the mask is short for amounts %s\n", sz, bad.empty() ? "(none below 200)" : bad.c_str());
  }
  long tot = 0;
  for (auto &kv : G) { std::printf("%-22s %12ld values %8ld outside the mask%s%s\n", kv.first.c_str(), kv.second.first, kv.second.second, kv.second.second ? "   e.g. " : "", EX[kv.first].c_str()); tot += kv.second.second; }
  std::printf("unsound masks: %ld\n", tot);
  return 0;
}
'''
open(out, "w").write(prog)
