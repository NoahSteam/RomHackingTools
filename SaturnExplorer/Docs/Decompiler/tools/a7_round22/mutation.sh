#   A7-170 (grammar 2 9404185), A5-147 (9408552, SE_A7_RULE_OFF=5147), A5-148 (grammar 2 9404677, 5148),
#   A5-146 (8902817, fixed by A5-144's rule: SE_A7_RULE_OFF=5144).
# The default run (every pin) with each rule off reports the pins' CHECK failures.
S=${SCRATCH:?set SCRATCH to a scratch directory}
B=$1
ulimit -v 6000000
count() { grep -o 'failing seeds=[0-9]*; findings=[0-9]*\|[0-9]* finding(s)' | tail -1; }
seed() { # <rule> <grammar> <seed> [alphabet]
  local alpha=${4:-none} on off
  on=$(env SE_GENERATED_ALPHABET=$alpha SE_GENERATED_GRAMMAR=$2 SE_GENERATED_SEED=$3 SE_GENERATED_CANARY=0 SE_GENERATED_SHRINK=0 "$B" "$S/mutseed" 2>&1 | count)
  off=$(env SE_A7_RULE_OFF=$1 SE_GENERATED_ALPHABET=$alpha SE_GENERATED_GRAMMAR=$2 SE_GENERATED_SEED=$3 SE_GENERATED_CANARY=0 SE_GENERATED_SHRINK=0 "$B" "$S/mutseed" 2>&1 | count)
  echo "seed $3 (grammar $2 $alpha): rule on: $on; SE_A7_RULE_OFF=$1: $off"
}
shrunk() { # <label> <rule> <words> [env assignments...]
  local label=$1 rule=$2 words=$3
  shift 3
  local on off
  on=$(env "$@" SE_GENERATED_WORDS="$words" SE_GENERATED_CANARY=0 "$B" "$S/mutshr" 2>&1 | count)
  off=$(env "$@" SE_A7_RULE_OFF=$rule SE_GENERATED_WORDS="$words" SE_GENERATED_CANARY=0 "$B" "$S/mutshr" 2>&1 | count)
  echo "$label shrunk: rule on: $on; SE_A7_RULE_OFF=$rule: $off"
}
