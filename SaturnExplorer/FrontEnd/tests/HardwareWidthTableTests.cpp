int main(int argc, char** argv)
{
    if (argc < 4)
    {
        std::printf("usage: %s <golden file> <audit document> <Mednafen handler cases>\n", argv[0]);
        return 2;
    }
    const std::string goldenPath = argv[1], auditPath = argv[2], casesPath = argv[3];
    const bool update = std::getenv("SE_UPDATE_GOLDEN") != nullptr;

    const std::vector<WidthProbe> table = WidthTable();
    std::string rules;
    const std::string text = Generate(table, rules);

    // Shape: every register is in, every cell has a rule whose text (when it has one) names the register.
    size_t n = 0;
    const HardwareRegister* regs = SaturnHardwareRegisters(n);
    std::map<const HardwareRegister*, size_t> perRegister;
    for (const WidthProbe& p : table) ++perRegister[p.reg];
    for (size_t i = 0; i < n; ++i) CHECK(perRegister[&regs[i]] >= 4);   // a byte/word/long write and a read, at least
    CHECK(table.size() > 3000);
    for (const WidthProbe& p : table)
    {
        CHECK(p.width == 1 || p.width == 2 || p.width == 4);
        CHECK(static_cast<int>(p.cell.rule) <= static_cast<int>(WidthRule::Undecoded));
        // The same cell asked again, by address, is the same cell (CoveredRegisters / NarrowAccessEffects use the address).
        const std::vector<CoveredRegister> c = CoveredRegisters(p.access, p.width, p.write);
        bool found = false;
        for (const CoveredRegister& x : c) found |= x.reg == p.reg && x.cell.rule == p.cell.rule;
        CHECK(found || p.cell.rule == WidthRule::AccessKind);
    }
    // A cell that is not (a) or "kind" says something: the generator has a caution for it.
    for (const WidthProbe& p : table)
    {
        const char cat = WidthCategory(p.cell.rule);
        if (cat == 'a' || cat == '-' || cat == 'v' || cat == '?') continue;
        bool said = false;
        for (const NarrowEffect& e : NarrowAccessEffects(p.access, p.width, p.write))
            said |= e.reg == p.reg && e.caution && (e.text.find(p.reg->name) != std::string::npos || std::string(p.reg->name).compare(0, 12, "SMPC_UNUSED_") == 0);
        CHECK(said);
    }

    // The golden file.
    if (update)
    {
        CHECK(WriteFile(goldenPath, text));
        std::printf("rewrote %s\n", goldenPath.c_str());
    }
    std::string golden;
    if (!ReadFile(goldenPath, golden))
    {
        std::printf("cannot read the golden file %s\n", goldenPath.c_str());
        ++gFailures;
    }
    else if (golden != text)
    {
        std::printf("the width table differs from the checked-in golden file %s\n", goldenPath.c_str());
        ShowFirstDifference("golden file", golden, text);
        ++gFailures;
    }

    // The audit document's copy of the rules table.
    std::string audit;
    if (!ReadFile(auditPath, audit))
    {
        std::printf("cannot read the audit document %s\n", auditPath.c_str());
        ++gFailures;
    }
    else
    {
        const std::string block = std::string(kRulesBegin) + "\n\n" + rules + "\n" + kRulesEnd;
        const size_t b = audit.find("<!-- width-rules:begin"), e = audit.find(kRulesEnd);
        if (b == std::string::npos || e == std::string::npos || e < b)
        {
            std::printf("the audit document has no width-rules block\n");
            ++gFailures;
        }
        else
        {
            const std::string have = audit.substr(b, e + std::strlen(kRulesEnd) - b);
            if (have != block)
            {
                if (update)
                {
                    audit.replace(b, have.size(), block);
                    CHECK(WriteFile(auditPath, audit));
                    std::printf("rewrote the width-rules block of %s\n", auditPath.c_str());
                }
                else
                {
                    std::printf("the width-rules block of %s differs from the table\n", auditPath.c_str());
                    ShowFirstDifference("audit block", have, block);
                    ++gFailures;
                }
            }
        }
    }

    // The independent check: the table against Mednafen's handlers (derive_handler_cases.py).
    {
        hhc::Cases cases;
        std::string error;
        if (!cases.Load(casesPath, error))
        {
            std::printf("%s\n", error.c_str());
            ++gFailures;
        }
        else
        {
            hhc::Stats st;
            hhc::Problems pr;
            // Decided not to be said, with the reason: starting a DMA transfer is what a write to the channel control
            // register or DMAOR is for, and a note on every one would bury the rare note.
            static const std::vector<hhc::Excused> excused = {
                { "SH2_CHCR0", "write:S", "a write to a DMA channel control register starts the transfer: the register's purpose" },
                { "SH2_CHCR1", "write:S", "as CHCR0" },
                { "SH2_DMAOR", "write:S", "a write that sets DME starts any channel that is ready: the register's purpose" },
            };
            hhc::CheckOnChip(cases, table, excused, st, pr);
            hhc::CheckUndecoded(cases, st, pr);
            hhc::CheckScu(cases, table, st, pr);
            hhc::CheckBlocks(cases, st, pr);
            hhc::CheckBus(cases, table, st, pr);
            hhc::CheckOnChipAddresses(cases, st, pr);
            if (!pr.list.empty())
            {
                std::printf("the width table disagrees with Mednafen's handlers (%zu):\n", pr.list.size());
                const size_t shown = std::getenv("SE_HANDLER_CHECK_ALL") ? pr.list.size() : 60;
                for (size_t i = 0; i < pr.list.size() && i < shown; ++i) std::printf("  %s\n", pr.list[i].c_str());
                if (pr.list.size() > shown) std::printf("  ... and %zu more\n", pr.list.size() - shown);
                gFailures += int(pr.list.size());
            }
            std::printf("handler check: %zu on-chip cells (%zu reach a case, %zu do not; %zu address errors), %zu SCU cells, %zu block registers, "
                        "%zu unnamed-address probes, %zu bus probes, %zu effect cells, %zu undecoded registers\n",
                        st.onchipCells, st.reached, st.unreached, st.errors, st.scuCells, st.blockRegs, st.unnamedAddresses, st.busFacts, st.effects,
                        st.undecodedRegs);
        }
    }

    if (gFailures)
    {
        std::printf("%d failure(s)\n", gFailures);
        return 1;
    }
    std::printf("HardwareWidthTableTests: %zu registers, %zu cells, all passed\n", n, table.size());
    return 0;
}
