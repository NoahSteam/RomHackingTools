int gFailures = 0;
#define CHECK(c)                                                                         \
    do                                                                                   \
    {                                                                                    \
        if (!(c))                                                                        \
        {                                                                                \
            std::printf("CHECK failed at %s:%d: %s\n", __FILE__, __LINE__, #c);          \
            ++gFailures;                                                                 \
        }                                                                                \
    } while (0)

const char* kRulesBegin = "<!-- width-rules:begin (generated by HardwareWidthTableTests; SE_UPDATE_GOLDEN=1 rewrites it) -->";
const char* kRulesEnd = "<!-- width-rules:end -->";

std::string Hex8(uint32_t a)
{
    char b[16];
    std::snprintf(b, sizeof b, "%08X", a);
    return b;
}

std::string Escape(std::string s)
{
    for (size_t at = s.find('|'); at != std::string::npos; at = s.find('|', at + 2)) s.replace(at, 1, "\\|");
    return s;
}

const char* AccessName(RegisterAccess a)
{
    switch (a)
    {
    case RegisterAccess::ReadWrite: return "RW";
    case RegisterAccess::ReadOnly: return "RO";
    case RegisterAccess::WriteOnly: return "WO";
    case RegisterAccess::KeyedWrite: return "KW";
    }
    return "?";
}

// "w4@-2=HalfOfLong[15-0]*": direction, width, offset from the register, the rule, the bits that
// reach it, and the flags: * the register's own effect happens, ! it has one and it does not, > the
// bus reads the register 2 bytes on as well, x2 the bus reads this one twice.
std::string Cell(const WidthProbe& p)
{
    std::string s = std::string(p.write ? "w" : "r") + std::to_string(p.width) + "@" + std::to_string(p.off);
    if (p.access - static_cast<uint32_t>(p.off) != p.reg->address) s += "^" + Hex8(p.access);
    s += std::string("=") + WidthRuleName(p.cell.rule);
    if (p.cell.hi || p.cell.lo) s += "[" + std::to_string(p.cell.hi) + "-" + std::to_string(p.cell.lo) + "]";
    const bool has = p.write ? p.reg->onWrite != nullptr : p.reg->onRead != nullptr;
    if (has) s += (p.cell.flags & kWidthEffect) ? "*" : "!";
    if (p.cell.flags & kWidthReadsNext) s += ">";
    if (p.cell.flags & kWidthReadsTwice) s += "x2";
    return s;
}

// The rules, their categories, where Mednafen has them, and the caution the first cell that uses
// each generates: the same lines go into the golden file and into the audit document.
std::string RulesTable(const std::vector<WidthProbe>& table)
{
    std::ostringstream o;
    o << "| Cat | Rule | Mednafen | Cells | Caution (first cell) |\n|---|---|---|---|---|\n";
    for (int i = 0; i <= static_cast<int>(WidthRule::Undecoded); ++i)
    {
        const WidthRule rule = static_cast<WidthRule>(i);
        size_t cells = 0;
        const WidthProbe* first = nullptr;
        for (const WidthProbe& p : table)
            if (p.cell.rule == rule)
            {
                ++cells;
                if (!first) first = &p;
            }
        std::string text = "(none)";
        if (first)
        {
            // Through the generator itself, the way the decompiler asks for it.
            for (const NarrowEffect& e : NarrowAccessEffects(first->access, first->width, first->write))
                if (e.reg == first->reg && e.caution && e.text.find("cache read") == std::string::npos)   // the bus's cache caution is the address's, not the cell's
                {
                    text = e.text + "  [" + first->reg->name + ", " + (first->write ? "write" : "read") + " " +
                           std::to_string(first->width) + " @" + Hex8(first->access) + "]";
                    break;
                }
        }
        o << "| " << WidthCategory(rule) << " | " << WidthRuleName(rule) << " | " << Escape(WidthRuleSource(rule)) << " | "
          << cells << " | " << Escape(text) << " |\n";
    }
    return o.str();
}

std::string FamilyTable()
{
    struct Row { size_t count = 0; std::string first, last; };
    std::map<int, Row> rows;
    size_t n = 0;
    const HardwareRegister* regs = SaturnHardwareRegisters(n);
    for (size_t i = 0; i < n; ++i)
    {
        Row& r = rows[static_cast<int>(regs[i].narrow)];
        if (!r.count++) r.first = regs[i].name;
        r.last = regs[i].name;
    }
    std::ostringstream o;
    o << "| Family | Registers | First .. last |\n|---|---|---|\n";
    for (const auto& kv : rows)
        o << "| " << WidthFamilyName(static_cast<NarrowAccess>(kv.first)) << " | " << kv.second.count << " | " << kv.second.first
          << " .. " << kv.second.last << " |\n";
    return o.str();
}

std::string Generate(const std::vector<WidthProbe>& table, std::string& rulesOnly)
{
    std::ostringstream o;
    o << "# SaturnHardwareMap width table\n"
         "# Generated by SaturnExplorerHardwareWidthTableTests from FrontEnd/src/Decompiler/SaturnHardwareMap.cpp; do not edit by hand\n"
         "# (SE_UPDATE_GOLDEN=1 rewrites it). Diff it against Mednafen: sh7095.inc, ss.c, scu.inc, vdp1.c, vdp2.c, cdb.c.\n"
         "#\n"
         "# A cell is  <w|r><width>@<offset of the access from the register>[^<bus address>]=<rule>[<bits of the value>]<flags>\n"
         "# flags: * the register's own read/write effect happens, ! it has one and the access does not do it,\n"
         "#        > the 32-bit bus also reads the register 2 bytes on, x2 it reads this one twice.\n"
         "# Categories: a accepted, b whole register, c one lane / half / register, d nothing, e address error,\n"
         "#             f side effect differs, v depends on the value (keyed), - the register's kind says it, ? not decoded.\n\n";
    rulesOnly = RulesTable(table);
    o << "## Rules\n\n" << rulesOnly << "\n## Families\n\n" << FamilyTable() << "\n";

    size_t registers = 0, lanes = 0;
    std::map<char, size_t> cats;
    for (const WidthProbe& p : table) ++cats[WidthCategory(p.cell.rule)];
    {
        size_t n = 0;
        SaturnHardwareRegisters(n);
        registers = n;
    }
    for (const WidthProbe& p : table) lanes += std::string(p.reg->name).compare(0, 12, "SMPC_UNUSED_") == 0 && p.width == 1 && p.write;
    o << "## Totals\n\n" << registers << " registers, " << lanes << " unused SMPC lanes, " << table.size() << " cells:";
    for (const auto& kv : cats) o << " " << kv.first << "=" << kv.second;
    o << "\n\n## Keyed writes\n\nThe cells marked KeyedWrite depend on the value: KeyedWrite() says what the key does. "
         "Address, width, value (? unknown), what it says:\n\n";
    {
        struct Sample { uint32_t address, size; bool known; uint32_t value; };
        const Sample samples[] = {
            { 0xFFFFFFE0u, 4, true, 0x00000003u }, { 0xFFFFFFE0u, 4, true, 0xA55A0003u }, { 0xFFFFFFE0u, 4, false, 0 },
            { 0xFFFFFFE4u, 4, true, 0x5A5A0003u }, { 0xFFFFFFF8u, 4, true, 0xA55A00FFu }, { 0xFFFFFFF0u, 4, false, 0 },
            { 0xFFFFFFE0u, 2, true, 0xA55Au },
            { 0xFFFFFE80u, 2, true, 0x5A12u }, { 0xFFFFFE80u, 2, true, 0xA512u }, { 0xFFFFFE80u, 2, true, 0x1234u },
            { 0xFFFFFE80u, 2, false, 0 }, { 0xFFFFFE82u, 2, true, 0xA500u }, { 0xFFFFFE82u, 2, true, 0x5A60u },
            { 0xFFFFFE82u, 2, true, 0x1234u }, { 0xFFFFFE82u, 2, false, 0 }, { 0xFFFFFE80u, 1, true, 0x12u },
        };
        for (const Sample& s : samples)
        {
            std::string t;
            bool ignored = false;
            const bool keyed = KeyedWrite(s.address, s.size, s.known, s.value, t, ignored);
            char head[64];
            std::snprintf(head, sizeof head, "%08X w%u ", s.address, s.size);
            o << head;
            if (s.known) o << "0x" << Hex8(s.value); else o << "?";
            o << " -> " << (keyed ? (ignored ? "[caution] " : "[note] ") + t : std::string("(not a keyed write)")) << "\n";
        }
    }
    o << "\n## Cells\n\n";

    // One line per register (and per window of the CD FIFO): all its cells, writes first.
    size_t i = 0;
    while (i < table.size())
    {
        size_t j = i;
        while (j < table.size() && table[j].reg == table[i].reg) ++j;
        const HardwareRegister& r = *table[i].reg;
        o << Hex8(r.address) << " " << r.name << " " << unsigned(r.size) << " " << AccessName(r.access) << " "
          << WidthFamilyName(r.narrow) << " |";
        for (size_t k = i; k < j; ++k) o << " " << Cell(table[k]);
        o << "\n";
        i = j;
    }
    return o.str();
}

bool ReadFile(const std::string& path, std::string& out)
{
    std::ifstream f(path, std::ios::binary);
    if (!f) return false;
    std::ostringstream s;
    s << f.rdbuf();
    out = s.str();
    return true;
}

bool WriteFile(const std::string& path, const std::string& text)
{
    std::ofstream f(path, std::ios::binary | std::ios::trunc);
    f << text;
    return bool(f);
}

// Where two texts first differ, so a failure says which line to read.
void ShowFirstDifference(const std::string& what, const std::string& want, const std::string& got)
{
    std::istringstream a(want), b(got);
    std::string x, y;
    for (int line = 1;; ++line)
    {
        const bool ax = static_cast<bool>(std::getline(a, x)), by = static_cast<bool>(std::getline(b, y));
        if (!ax && !by) return;
        if (!ax || !by || x != y)
        {
            std::printf("%s differs at line %d:\n  checked in: %s\n  generated : %s\n", what.c_str(), line, ax ? x.c_str() : "<end>",
                        by ? y.c_str() : "<end>");
            return;
        }
    }
}
