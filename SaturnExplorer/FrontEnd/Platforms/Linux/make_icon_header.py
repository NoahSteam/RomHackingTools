#!/usr/bin/env python3
"""Regenerate SaturnExplorerIcon.h, the Linux window icon, from the Windows .ico (the same source the
macOS .icns comes from). Needs Pillow. Run from anywhere:  python3 FrontEnd/Platforms/Linux/make_icon_header.py"""
import os

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
SIZE = 64   # X11/Wayland scale it; larger only grows the binary

ico = Image.open(os.path.join(HERE, "..", "Windows", "SaturnExplorer.ico"))
ico.size = max(ico.info["sizes"])            # decode the largest frame, then scale it down
pixels = ico.convert("RGBA").resize((SIZE, SIZE), Image.LANCZOS).tobytes()
rows = [", ".join(str(b) for b in pixels[i:i + 32]) for i in range(0, len(pixels), 32)]
with open(os.path.join(HERE, "SaturnExplorerIcon.h"), "w", newline="\n") as f:
    f.write("// Generated by make_icon_header.py from Platforms/Windows/SaturnExplorer.ico; do not edit.\n"
            "#pragma once\n\n"
            f"static const int kSaturnExplorerIconSize = {SIZE};\n"
            "// RGBA, row-major, top row first.\n"
            "static const unsigned char kSaturnExplorerIconRgba[] = {\n    " + ",\n    ".join(rows) + "\n};\n")
